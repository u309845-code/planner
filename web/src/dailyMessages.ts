/** Шаг взаимно прост с длиной списка, поэтому соседние дни не получают соседние фразы. */
const STEP = 7

/** Одно и то же послание весь день; на следующий день — другое. */
export function messageForDay(ms: number): string {
  const d = new Date(ms)
  const dayNumber = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86_400_000)
  return MESSAGES[(dayNumber * STEP) % MESSAGES.length]
}

export function greetingFor(ms: number): string {
  const h = new Date(ms).getHours()
  if (h >= 5 && h < 12) return 'Доброе утро'
  if (h >= 12 && h < 18) return 'Добрый день'
  if (h >= 18 && h < 23) return 'Добрый вечер'
  return 'Доброй ночи'
}
